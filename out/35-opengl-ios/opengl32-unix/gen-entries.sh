# gen-entries.sh <opengl32 unixlib.h> <out header>
#
# Spec 35 Part E3/E4: writes one line per entry of opengl32's enum unix_funcs, in enum order,
#   OPENGL_IOS_ENTRY( unix_<name> )
# and OPENGL_IOS_ENTRY_COUNT, the number of entries. opengl_ios_tables.c turns the list into
# the wrapper of every entry (both tables) and the names of the call statistics, so every entry
# is covered by construction. The header is the one make_opengl wrote (both halves of opengl32
# come from one generator run, Part A3). Fails when the enum isn't found or doesn't end at
# funcs_count.

set -eu
[ $# -eq 2 ] || { echo "usage: $0 <unixlib.h> <out header>" >&2; exit 2; }

tmp="$2.tmp"
tr -d '\r' < "$1" | awk '
    /^enum unix_funcs$/ { in_enum = 1; next }
    in_enum && /^\{/ { next }
    in_enum && /^ *funcs_count/ { done = 1; in_enum = 0; next }
    in_enum && /^ *unix_[A-Za-z0-9_]+,/ {
        name = $1; sub(/,$/, "", name)
        printf "OPENGL_IOS_ENTRY( %s )\n", name
        n++
        next
    }
    in_enum && /^\};/ { in_enum = 0 }
    END {
        if (!done || !n) { print "gen-entries.sh: enum unix_funcs ... funcs_count not found" > "/dev/stderr"; exit 1 }
        printf "#define OPENGL_IOS_ENTRY_COUNT %d\n", n
    }
' > "$tmp"
{
    echo "/* Generated by gen-entries.sh from $(basename "$1"); do not edit. */"
    cat "$tmp"
} > "$2"
rm -f "$tmp"
