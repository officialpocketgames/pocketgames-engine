# Spec 09 Part A: compile ntdll's unix side (dlls/ntdll/unix/ of Wine 11.4, with this spec's
# replacements and new files) for iOS arm64 into one static library, libntdll_unix.a.
#
# usage: build-ios.sh <wine-11.4 tree> <wine build dir> <out dir>
#
#   <wine-11.4 tree>  the upstream source tree (refs/wine-11.4)
#   <wine build dir>  a host (macOS) configure + "make include/all" of the same tree: it holds
#                     include/config.h, include/wine/server_protocol.h and the other generated
#                     headers
#   <out dir>         receives src/ (the merged sources), obj/, logs/ and libntdll_unix.a
#
# Environment:
#   CC             the compiler (default: xcrun -sdk iphoneos clang)
#
# No IOKit: it isn't public API on iOS (spec 00 B1). cdrom.c's and system.c's IOKit paths are
# compiled out under WINE_IOS, so an IOKit include that reappears fails the build.
#
# Every .c file of dlls/ntdll/unix/ is compiled (the per-architecture signal_*.c files are empty
# on arm64), plus the new ios_*.c files. unix/version.c is not: the app provides wine_build
# (interfaces/wine_unix_contract.h Section B).
#
# Prints "<name> OK" or "<name> FAILED" for each file, then the compiler errors of every failed
# file, and exits non-zero if any file failed.

set -u

if [ $# -ne 3 ]; then
  echo "usage: $0 <wine-11.4 tree> <wine build dir> <out dir>" >&2
  exit 2
fi

abspath() {
  (cd "$1" 2>/dev/null && pwd) || { echo "no such directory: $1" >&2; exit 2; }
}

WINE=$(abspath "$1") || exit 2
BUILD=$(abspath "$2") || exit 2
mkdir -p "$3" || exit 2
OUT=$(abspath "$3") || exit 2
HERE=$(abspath "$(dirname "$0")") || exit 2
MINE="$HERE/ntdll-unix"
# spec 17 Part A1: the shared header overrides (wine/unixlib.h, winternl.h), searched before the
# Wine tree's include/
OVERRIDE_INC="$HERE/include"
# spec 09 clarification 2: spec 13's socket.c (and its header) replaces upstream's
SOCKET_SRC="$HERE/../13-net-crypto-ios/ntdll-unix"
# spec 09 clarification 5 (spec 16): the synchronization library (the cell table, the userspace
# ntsync engine, ...) is compiled into this library, one copy per app; its include/ holds the
# stand-in <linux/ntsync.h>
SYNC_DIR="$HERE/../16-sync-ios"

[ -f "$WINE/dlls/ntdll/unix/loader.c" ] || { echo "not a wine tree: $WINE" >&2; exit 2; }
[ -f "$BUILD/include/config.h" ] || { echo "no include/config.h in $BUILD" >&2; exit 2; }
[ -f "$BUILD/include/wine/server_protocol.h" ] || [ -f "$WINE/include/wine/server_protocol.h" ] || {
  echo "no include/wine/server_protocol.h in $BUILD or $WINE" >&2; exit 2; }

SRC="$OUT/src"
OBJ="$OUT/obj"
LOG="$OUT/logs"
rm -rf "$SRC" "$OBJ" "$LOG" "$OUT/shim"
mkdir -p "$SRC" "$OBJ" "$LOG"

# 1. upstream sources, then ours on top (replacements and new files)
cp "$WINE"/dlls/ntdll/unix/*.c "$WINE"/dlls/ntdll/unix/*.h "$SRC"/ || exit 1
cp "$MINE"/*.c "$MINE"/*.h "$SRC"/ || exit 1
cp "$SOCKET_SRC/socket.c" "$SOCKET_SRC/ios_afd.h" "$SRC"/ || exit 1

# 2. config.h: the host configure's, then the iOS adjustments. A source file's own directory
#    is searched first for "config.h", so this wrapper wins over the build dir's.
{
  echo "/* generated by build-ios.sh: host config.h, then the iOS adjustments */"
  echo "#include \"$BUILD/include/config.h\""
  echo "#include \"ios_config.h\""
} > "$SRC/config.h"

CC=${CC:-"xcrun -sdk iphoneos clang"}
AR=${AR:-"xcrun -sdk iphoneos ar"}

COMMON="-arch arm64 -miphoneos-version-min=17.0 -O2 -std=gnu11 -fPIC -fno-strict-aliasing \
 -fasynchronous-unwind-tables -fno-omit-frame-pointer -ffixed-x18"
DEFS="-DWINE_IOS=1 -DWINE_UNIX_LIB -D__WINESRC__ -D_NTSYSTEM_ -D_ACRTIMP= -DWINBASEAPI= -D_REENTRANT"
DEFS="$DEFS -DHAVE_LINUX_NTSYNC_H=1 -DIOS_USYNC=1"   # spec 16 E5 (ios_config.h keeps it)
WARN="-Wall -Wno-unused-function -Wno-unused-variable -Wno-unused-but-set-variable \
 -Wno-pragma-pack -Wno-deprecated-declarations -Wno-unknown-pragmas"
# interfaces/: wine_unix_contract.h, the app's side of the contract (Section B hooks)
INC="-I$SRC -I$SYNC_DIR/include -I$WINE/dlls/ntdll -I$BUILD/dlls/ntdll -I$OVERRIDE_INC -I$BUILD/include -I$WINE/include -I$HERE/../../interfaces"
FORCE="-include $SRC/ios_noexit.h -include $SRC/ios_rename.h"
# loader.c derives bin_dir and data_dir from the directory of the binary that holds ntdll's unix
# side (the app's executable, found with dladdr) relative to LIBDIR/wine. With these values both
# are that directory itself: the NLS tables are read from <app bundle>/nls/, as the server's
# fallback (spec 08 Part B5).
LOADER_DEFS="-DBINDIR=\"/usr/local/wine\" -DLIBDIR=\"/usr/local\" -DDATADIR=\"/usr/local\" -DSYSTEMDLLPATH=\"\""

failed=""
for c in "$SRC"/*.c; do
  name=$(basename "$c" .c)
  extra=""
  [ "$name" = loader ] && extra="$LOADER_DEFS"
  # shellcheck disable=SC2086
  if $CC $COMMON $DEFS $extra $WARN $INC $FORCE -c "$c" -o "$OBJ/$name.o" > "$LOG/$name.log" 2>&1; then
    echo "$name OK"
  else
    echo "$name FAILED"
    failed="$failed $name"
  fi
done

# spec 16: its own sources (plain C, no Wine header), into the same library
for c in "$SYNC_DIR"/src/*.c; do
  name=sync16_$(basename "$c" .c)
  # shellcheck disable=SC2086
  if $CC $COMMON -Wall -I"$SYNC_DIR/include" -c "$c" -o "$OBJ/$name.o" > "$LOG/$name.log" 2>&1; then
    echo "$name OK"
  else
    echo "$name FAILED"
    failed="$failed $name"
  fi
done

if [ -n "$failed" ]; then
  for name in $failed; do
    echo "===== $name ====="
    cat "$LOG/$name.log"
  done
  exit 1
fi

rm -f "$OUT/libntdll_unix.a"
# shellcheck disable=SC2086
$AR rcs "$OUT/libntdll_unix.a" "$OBJ"/*.o || exit 1
echo "wrote $OUT/libntdll_unix.a"

# clarification 6: every symbol the loader looks up by name (unixlibs.txt), for the app's
# build check (TESTS.md: `nm -gU` of the app must list each one)
sh "$HERE/write-exports.sh" "$HERE/unixlibs.txt" > "$OUT/exports.txt" || exit 1
echo "wrote $OUT/exports.txt ($(wc -l < "$OUT/exports.txt") symbols)"
