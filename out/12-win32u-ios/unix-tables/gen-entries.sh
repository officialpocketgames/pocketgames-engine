# gen-entries.sh <upstream header> <enum name> <count entry> <output .h> [setup entry...]
#
# Spec 12 clarifications 8 and 9: reads the call enum of a Wine 11.4 unix library (for example
# "enum unix_funcs" ending at "funcs_count" in dlls/opengl32/unixlib.h) and writes one line per
# entry before the count entry:
#     W32IOS_UNIX_SETUP( unix_<name> )         for the setup entries named on the command line
#     W32IOS_UNIX_UNSUPPORTED( unix_<name> )   for every other entry
# and last "#define W32IOS_UNIX_ENTRY_COUNT <n>", n counting all of them. unix_table_ios.inc
# includes the output and checks n against the count entry at compile time. Fails, writing
# nothing, when the enum isn't found, a line isn't a plain "unix_<name>," entry, or a named setup
# entry is missing. Never writes into the repository's refs/.

set -eu

if [ $# -lt 4 ]; then
  echo "usage: $0 <upstream header> <enum name> <count entry> <output .h> [setup entry...]" >&2
  exit 2
fi
HEADER=$1; ENUM=$2; COUNT=$3; OUTPUT=$4
shift 4

REPO=$(cd "$(dirname "$0")/../../.." && pwd -P)
OUT_DIR=$(cd "$(dirname "$OUTPUT")" && pwd -P)
case "$OUT_DIR/" in
  "$REPO/refs/"*) echo "$0: refusing to write into refs/: $OUTPUT" >&2; exit 1 ;;
esac
OUT="$OUT_DIR/$(basename "$OUTPUT")"

awk -v src="$HEADER" -v enum_name="$ENUM" -v count="$COUNT" -v setup_list="$*" '
BEGIN {
    print "/* generated by gen-entries.sh from " src " (enum " enum_name "); do not edit */"
    split( "", setup )
    wanted = split( setup_list, names, " " )
    for (i = 1; i <= wanted; i++) setup[names[i]] = 1
}
!inside && $1 == "enum" && $2 == enum_name { inside = 1; next }
inside {
    line = $0
    gsub( /[ \t,\r]/, "", line )
    if (line == "" || line == "{") next
    if (line == count) { done = 1; exit }
    if (line !~ /^unix_[A-Za-z0-9_]+$/) { bad = line; exit }
    n++
    if (line in setup) { found++; print "W32IOS_UNIX_SETUP( " line " )" }
    else print "W32IOS_UNIX_UNSUPPORTED( " line " )"
}
END {
    if (bad != "") { print "gen-entries.sh: unexpected line in enum " enum_name ": " bad > "/dev/stderr"; exit 1 }
    if (!done) { print "gen-entries.sh: enum " enum_name " ending at " count " not found in " src > "/dev/stderr"; exit 1 }
    if (found != wanted) { print "gen-entries.sh: " found + 0 " of the " wanted " setup entries found in enum " enum_name > "/dev/stderr"; exit 1 }
    print "#define W32IOS_UNIX_ENTRY_COUNT " n
}' "$HEADER" > "$OUT.tmp" || { rm -f "$OUT.tmp"; exit 1; }
mv "$OUT.tmp" "$OUT"
