# Spec 34 Part M6: builds vktest.exe for x86_64 and i686 with llvm-mingw (CI; never run here).
#
#   build-vktest.sh <llvm-mingw bin dir> <Vulkan-Headers include dir> <out dir>
#
# The shaders of shaders/ go to SPIR-V with glslangValidator (a build tool only: the SPIR-V is
# data inside the test program; nothing of glslang is linked) as C arrays in vktest_shaders.h.
# <Vulkan-Headers include dir> holds vulkan/vulkan.h (Khronos Vulkan-Headers, the revision the
# MoltenVK fork pins). Writes <out dir>/vktest-x86_64.exe and vktest-i686.exe.

set -eu
[ $# -eq 3 ] || { echo "usage: $0 <llvm-mingw bin dir> <Vulkan-Headers include dir> <out dir>" >&2; exit 2; }
here=$(cd "$(dirname "$0")" && pwd)
bin=$(cd "$1" && pwd)
vkinc=$(cd "$2" && pwd)
mkdir -p "$3"
out=$(cd "$3" && pwd)
[ -f "$vkinc/vulkan/vulkan.h" ] || { echo "build-vktest: no vulkan/vulkan.h in $vkinc" >&2; exit 1; }
command -v glslangValidator >/dev/null 2>&1 || { echo "build-vktest: glslangValidator is needed (glslang-tools)" >&2; exit 1; }

gen="$out/gen"
mkdir -p "$gen"
{
    echo "/* generated by build-vktest.sh from shaders/ with glslangValidator; do not edit */"
    echo "#include <stdint.h>"
} > "$gen/vktest_shaders.h"
for s in cube.vert cube.frag solid.vert solid.frag tess.tesc tess.tese; do
    name=$(echo "$s" | tr '.' '_')
    glslangValidator -V --target-env vulkan1.1 --vn "$name" -o "$gen/$name.h" "$here/shaders/$s"
    sed 's/^const uint32_t/static const uint32_t/' "$gen/$name.h" >> "$gen/vktest_shaders.h"
done
# the geometry-shader draw and transform-feedback capture (clarification 1), shared with the
# macOS render test
common="$here/../common"
sh "$common/gen-vkgx-shaders.sh" "$gen/vkgx_shaders.h"

for arch in x86_64 i686; do
    "$bin/$arch-w64-mingw32-clang" -std=gnu11 -O2 -Wall -Wextra -I"$vkinc" -I"$gen" -I"$common" \
        "$here/vktest.c" "$common/vkgx.c" -o "$out/vktest-$arch.exe" -luser32 -lkernel32 -lm
    echo "built $out/vktest-$arch.exe"
done
