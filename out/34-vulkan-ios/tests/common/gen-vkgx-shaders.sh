# Spec 34 clarification 1, item 6: the SPIR-V of shaders/ (the geometry-shader draw and the
# transform-feedback capture of vkgx.c) as C arrays in <out header>, with glslangValidator (a
# build tool only: nothing of glslang is linked). build-vktest.sh and tests/macos's
# build-render-test.sh both call it; the CI compiles, never this PC.
#
#   gen-vkgx-shaders.sh <out header>

set -eu
[ $# -eq 1 ] || { echo "usage: $0 <out header>" >&2; exit 2; }
here=$(cd "$(dirname "$0")" && pwd)
command -v glslangValidator >/dev/null 2>&1 || { echo "gen-vkgx-shaders: glslangValidator is needed (glslang)" >&2; exit 1; }
out=$1
tmp="$out.d"
mkdir -p "$tmp"
{
    echo "/* generated by gen-vkgx-shaders.sh from shaders/ with glslangValidator; do not edit */"
    echo "#include <stdint.h>"
} > "$out.part"
for s in gs_quad.vert gs_quad.geom gs_color.frag xfb.vert xfb.geom; do
    name=$(echo "$s" | tr '.' '_')
    glslangValidator -V --target-env vulkan1.1 --vn "$name" -o "$tmp/$name.h" "$here/shaders/$s"
    sed 's/^const uint32_t/static const uint32_t/' "$tmp/$name.h" >> "$out.part"
done
rm -rf "$tmp"
mv "$out.part" "$out"
echo "gen-vkgx-shaders: $out"
