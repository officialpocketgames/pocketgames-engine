# Spec 05 Part A: compile the unix half of DXMT (winemetal's unix side, the
# airconv shader converter and the DXBC parser) for iOS arm64.
#
# usage: build-ios.sh <dxmt-tree> <llvm-build-dir> <llvm-src-dir> <out-dir>
#
#   <dxmt-tree>       out/05-dxmt-ios/dxmt
#   <llvm-build-dir>  an LLVM 15.0.7 build tree (its include/ holds the generated
#                     headers such as llvm/Config/llvm-config.h)
#   <llvm-src-dir>    the llvm-project checkout (or its llvm/ subdirectory)
#   <out-dir>         receives obj/, shader-headers/ and libdxmt_unix.a
#
# Environment: METAL_STD (default metal3.1) is the Metal language version of
# the helper shaders, as the meson option metal_std is for the Windows half.
#
# Prints "<name> OK" or "<name> FAILED" for each file, then the compiler
# errors of every failed file, and exits non-zero if any file failed.

set -u

if [ $# -ne 4 ]; then
  echo "usage: $0 <dxmt-tree> <llvm-build-dir> <llvm-src-dir> <out-dir>" >&2
  exit 2
fi

abspath() {
  (cd "$1" 2>/dev/null && pwd) || { echo "no such directory: $1" >&2; exit 2; }
}

TREE=$(abspath "$1") || exit 2
LLVM_BUILD=$(abspath "$2") || exit 2
LLVM_SRC=$(abspath "$3") || exit 2
mkdir -p "$4" || exit 2
OUT=$(abspath "$4") || exit 2

OBJ="$OUT/obj"
HDR="$OUT/shader-headers"
LOG="$OUT/logs"
rm -rf "$OBJ" "$HDR" "$LOG"
mkdir -p "$OBJ" "$HDR" "$LOG"

METAL_STD=${METAL_STD:-metal3.1}

if [ -d "$LLVM_SRC/llvm/include" ]; then
  LLVM_SRC_INC="$LLVM_SRC/llvm/include"
else
  LLVM_SRC_INC="$LLVM_SRC/include"
fi

CC="xcrun -sdk iphoneos clang"
CXX="xcrun -sdk iphoneos clang++"
METAL="xcrun -sdk macosx metal"

COMMON="-arch arm64 -miphoneos-version-min=17.0 -fblocks -O2 -DDXMT_IOS=1"
WARN="-Wno-unused-parameter -Wno-unused-private-field -Wno-unused-const-variable -Wno-missing-braces -Wno-extern-c-compat"

INC_DXMT="-I$TREE/include -I$TREE/libs -I$TREE/include/native/windows -I$TREE/include/native/directx"
INC_LLVM="-I$LLVM_SRC_INC -I$LLVM_BUILD/include"

FAILED=""

# run_step <display-name> <log-name> <command...>
run_step() {
  name=$1
  log="$LOG/$2.log"
  shift 2
  if "$@" >"$log" 2>&1; then
    echo "$name OK"
  else
    echo "$name FAILED"
    FAILED="$FAILED $log"
  fi
}

# Object name from a path relative to the tree: src/airconv/nt/x.cpp -> src_airconv_nt_x.o
obj_name() {
  echo "$1" | sed -e 's|/|_|g' -e 's|\.[^.]*$|.o|'
}

# --- helper shaders -> C arrays (upstream: metalir_generator + hexdump_generator)

# gen_header <in.air> <array-name> <out.h>
gen_header() {
  {
    printf '/* Generated by build-ios.sh from %s.metal. */\n' "$2"
    printf 'static const unsigned char %s[] = {\n' "$2"
    od -An -v -tx1 "$1" | awk '{ s = "  "; for (i = 1; i <= NF; i++) s = s "0x" $i ","; print s }'
    printf '};\n'
  } >"$3"
}

# The shaders are found under the tree (the script may run from any directory),
# one .air and one header (array named after the file, as airconv_context.cpp
# expects) per shader.
SHADER_COUNT=0
for path in "$TREE"/src/airconv/shaders/*.metal; do
  [ -f "$path" ] || continue
  SHADER_COUNT=$((SHADER_COUNT + 1))
  base=$(basename "$path" .metal)
  air="$HDR/$base.air"
  run_step "$base.metal" "shader_$base" \
    $METAL -std="$METAL_STD" --target=air64-apple-macos14.0 -c "$path" -o "$air"
  if [ -f "$air" ]; then
    run_step "$base.h" "header_$base" gen_header "$air" "$base" "$HDR/$base.h"
  fi
done
if [ "$SHADER_COUNT" -eq 0 ]; then
  echo "helper shaders FAILED (none found in $TREE/src/airconv/shaders)"
  FAILED="$FAILED (helper shaders)"
fi

# --- winemetal unix side: Objective-C, manual reference counting (as upstream)

for src in src/winemetal/unix/winemetal_unix.c src/winemetal/unix/cache.c src/winemetal/unix/ios_support.m; do
  run_step "$(basename "$src")" "$(obj_name "$src" | sed 's/\.o$//')" \
    $CC $COMMON $WARN -x objective-c -fno-objc-arc \
      -I"$TREE/src/winemetal" -I"$TREE/src/airconv" $INC_DXMT \
      -c "$TREE/$src" -o "$OBJ/$(obj_name "$src")"
done

# --- airconv: the library sources of upstream's src/airconv/meson.build (not the CLI)

AIRCONV_SRC=$(awk '
  /^airconv_src = files\(\[/ { inside = 1; next }
  inside && /\]\)/ { inside = 0 }
  inside { print }
' "$TREE/src/airconv/meson.build" | tr -d " ,'" | grep '\.cpp$' | sed 's|^|src/airconv/|')

if [ -z "$AIRCONV_SRC" ]; then
  echo "airconv source list FAILED (could not read src/airconv/meson.build)"
  FAILED="$FAILED (airconv source list)"
fi

AIRCONV_FLAGS="-std=c++20 -fno-exceptions -fno-rtti -funwind-tables -D_FILE_OFFSET_BITS=64 \
  -D__STDC_CONSTANT_MACROS -D__STDC_FORMAT_MACROS -D__STDC_LIMIT_MACROS"

for src in $AIRCONV_SRC; do
  run_step "$(basename "$src")" "$(obj_name "$src" | sed 's/\.o$//')" \
    $CXX $COMMON $WARN -x c++ $AIRCONV_FLAGS \
      -I"$TREE/src/airconv" -I"$HDR" $INC_DXMT $INC_LLVM \
      -c "$TREE/$src" -o "$OBJ/$(obj_name "$src")"
done

# --- DXBCParser: C++20, exceptions on, RTTI off

for path in "$TREE"/libs/DXBCParser/*.cpp; do
  src="libs/DXBCParser/$(basename "$path")"
  run_step "$(basename "$src")" "$(obj_name "$src" | sed 's/\.o$//')" \
    $CXX $COMMON $WARN -x c++ -std=c++20 -fexceptions -fno-rtti -Wno-unknown-pragmas \
      -I"$TREE/include/native/windows" -I"$TREE/include/native/directx" \
      -c "$TREE/$src" -o "$OBJ/$(obj_name "$src")"
done

# --- archive

rm -f "$OUT/libdxmt_unix.a"
if [ -z "$FAILED" ]; then
  run_step "libdxmt_unix.a" "archive" xcrun -sdk iphoneos libtool -static -o "$OUT/libdxmt_unix.a" "$OBJ"/*.o
fi

if [ -n "$FAILED" ]; then
  echo
  echo "=== compiler errors ==="
  for log in $FAILED; do
    if [ -f "$log" ]; then
      echo "--- $(basename "$log" .log)"
      cat "$log"
    else
      echo "--- $log"
    fi
  done
  exit 1
fi

exit 0
